type RummyLocale = keyof typeof localeIndexes;
type Catalog = Readonly<Record<string, string>>;

/** Adds the rummy table's texts to each language's catalog. */
export function withRummyTexts(
	catalogs: Readonly<Record<RummyLocale, Catalog>>,
): Readonly<Record<RummyLocale, Catalog>> {
	return Object.fromEntries(
		Object.entries(localeIndexes).map(([locale, index]) => [
			locale,
			{
				...catalogs[locale as RummyLocale],
				...Object.fromEntries(rows.map((row) => [row[0], row[index]])),
			},
		]),
	) as Readonly<Record<RummyLocale, Catalog>>;
}
